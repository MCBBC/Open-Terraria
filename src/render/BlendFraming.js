function R(ci, ce, bi, be, s, e) {
    // "A1" 记法：行=字母-‘A’，列=数字-1；3 变体 = 起点/中点/终点
    const p = (t) => ({ col: parseInt(t.slice(1), 10) - 1, row: t.charCodeAt(0) - 65 });
    const a = p(s), b = p(e);
    const mid = { col: b.col - ((b.col - a.col) >> 1), row: b.row - ((b.row - a.row) >> 1) };
    return { ci, ce, bi, be, uvs: [a, mid, b] };
}
// 严格匹配（TEdit MatchRule.Matches）
function matches(r, neighborMask, blendMask) {
    const uci = (r.ci << 16) & 0x11110000;
    if ((uci & neighborMask) !== uci)
        return false;
    const uce = (r.ce << 16) & 0x11110000;
    if (uce !== 0 && (uce & neighborMask) !== 0)
        return false;
    const lbi = r.bi & 0x1111;
    if (lbi !== 0 && ((lbi ^ (blendMask & 0x1111)) !== 0))
        return false;
    const ubi = r.bi & 0x11110000;
    if ((ubi & blendMask) !== ubi)
        return false;
    const lbe = r.be & 0x1111;
    if ((lbe & blendMask) !== 0)
        return false;
    const ube = r.be & 0x11110000;
    if (ube !== 0 && (ube & blendMask) !== 0)
        return false;
    return true;
}
// 草专用松弛匹配（TEdit MatchesRelaxed）：角落包含位逐列 OR 判定
function matchesRelaxed(r, neighborMask, blendMask) {
    let column = 0x10000;
    for (let i = 0; i < 4; i++) {
        const uci = (r.ci << 16) & column;
        const ubi = r.bi & column;
        if ((uci & ubi) === 0) {
            if (uci !== 0 && (uci & neighborMask) === 0)
                return false;
            if (ubi !== 0 && (ubi & blendMask) === 0)
                return false;
        }
        else {
            if ((uci & neighborMask) === 0 && (ubi & blendMask) === 0)
                return false;
        }
        if (i < 3)
            column <<= 4;
    }
    const uce = (r.ce << 16) & 0x11110000;
    if (uce !== 0 && (uce & neighborMask) !== 0)
        return false;
    const lbi = r.bi & 0x1111;
    if (lbi !== 0 && ((lbi ^ (blendMask & 0x1111)) !== 0))
        return false;
    const lbe = r.be & 0x1111;
    if ((lbe & blendMask) !== 0)
        return false;
    const ube = r.be & 0x11110000;
    if (ube !== 0 && (ube & blendMask) !== 0)
        return false;
    return true;
}
const bucketOf = (m) => (((m & 0x1000) >> 9) + ((m & 0x100) >> 6) + ((m & 0x10) >> 3) + (m & 0x1));
/** 掩码 → 帧格（col,row）。strictness：0 普通 / 1 合并 / 2 草 */
export function getUVForMasks(neighborMask, blendMask, strictness, variant) {
    let bucketId = bucketOf(neighborMask);
    const v = Math.min(Math.max(0, variant), 2);
    if (strictness === 0) {
        for (const r of baseRules[bucketId])
            if (matches(r, neighborMask, blendMask))
                return r.uvs[v];
    }
    else if (strictness === 1) {
        for (const r of blendRules[bucketId])
            if (matches(r, neighborMask, blendMask))
                return r.uvs[v];
    }
    else {
        for (const r of grassRules[bucketId])
            if (matchesRelaxed(r, neighborMask, blendMask))
                return r.uvs[v];
        // 草无专用规则时：并上合并掩码再用普通表
        const nm = neighborMask | blendMask;
        bucketId = bucketOf(nm);
        for (const r of baseRules[bucketId])
            if (matches(r, nm, blendMask))
                return r.uvs[v];
    }
    return { col: 0, row: 0 };
}
