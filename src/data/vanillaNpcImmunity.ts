/** 派生规则（NPC.cs:17761-17772 SetDefaults 后置）:免疫 20(中毒) → 免疫 30(流血)+375;
 *  免疫 69(灵液) → 免疫 36(虚弱) */
function derive(ids: number[]): Set<number> {
  const s = new Set(ids);
  if (s.has(20)) { s.add(30); s.add(375); }
  if (s.has(69)) { s.add(36); }
  return s;
}
const CACHE = new Map<number, Set<number>>();
/** 该 NPC 是否免疫指定 vanilla buff id（NPC.AddBuff :90968 免疫即 return） */
export function npcImmuneTo(npcId: number, vanillaBuffId: number): boolean {
  let s = CACHE.get(npcId);
  if (!s) {
    const raw = DATA[String(npcId)];
    s = raw ? derive(raw) : new Set<number>();
    CACHE.set(npcId, s);
  }
  return s.has(vanillaBuffId);
}
