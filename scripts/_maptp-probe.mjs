// 地图点击传送探针:M 开图 → 同点两次点击 → 应传送(自研调试功能,原版双击归 ping)。
import puppeteer from 'puppeteer-core';
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const URL = (process.env.SW_ORIGIN ?? 'http://localhost:5199') + '/';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', protocolTimeout: 300000, defaultViewport: { width: 1280, height: 900 } });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(URL, { waitUntil: 'networkidle0' });
await page.waitForSelector('select', { timeout: 120000 });
await page.evaluate(() => { document.querySelector('select').selectedIndex = 0; });
await page.click('button');
await page.waitForFunction(() => window.__swGame && window.__swGame.world, { timeout: 300000 });
await new Promise((r) => setTimeout(r, 2500));
let pass = 0, fail = 0;
const check = (n, ok, x = '') => { console.log(`${ok ? 'PASS' : 'FAIL'}: ${n}${x ? '  ' + x : ''}`); ok ? pass++ : fail++; };

const out = await page.evaluate(async () => {
  const g = window.__swGame, pl = g.player;
  const o = {};
  o.pos0 = [pl.x, pl.y];
  g.toggleFullMap();
  await new Promise((r) => setTimeout(r, 150));
  o.mapOpen = !!g.renderer.fullMap.open;
  const fm = g.renderer.fullMap;
  const viewW = g.renderer.canvas.width, viewH = g.renderer.canvas.height;
  const cx0 = viewW / 2 - (g.world.w * fm.zoom) / 2 + fm.panX;
  const cy0 = viewH / 2 - (g.world.h * fm.zoom) / 2 + fm.panY;
  const tx = Math.floor(g.world.w / 2), ty = Math.floor(g.world.groundLevel ?? 100);
  const sx = (tx + 0.5) * fm.zoom + cx0, sy = (ty + 0.5) * fm.zoom + cy0;
  o.tpTile = [tx, ty]; o.screen = [Math.round(sx), Math.round(sy)];
  const press = async (x, y) => {
    g.input.mouseX = x; g.input.mouseY = y; g.input.mouseDown = true;
    await new Promise((r) => setTimeout(r, 60));
    g.input.mouseDown = false;
    await new Promise((r) => setTimeout(r, 150));
  };
  await press(sx, sy);
  o.tpTargetAfterFirst = g._tpTarget ? [g._tpTarget.x, g._tpTarget.y] : null;
  await new Promise((r) => setTimeout(r, 700));
  await press(sx, sy);
  await new Promise((r) => setTimeout(r, 900));
  o.posAfter = [Math.round(pl.x), Math.round(pl.y)];
  o.tpMoved = Math.hypot(pl.x - o.pos0[0], pl.y - o.pos0[1]) > 200;
  return o;
});
console.log(JSON.stringify(out));
check('M 键开全屏地图', out.mapOpen);
check('第一次点击出现传送预选(_tpTarget)', !!out.tpTargetAfterFirst, JSON.stringify(out.tpTargetAfterFirst));
check('第二次点击同点传送成功(位移>200px)', out.tpMoved, `${out.pos0} → ${out.posAfter}`);
check('无页面错误', errors.length === 0, errors.join(' | ').slice(0, 150));
await browser.close();
console.log(`\n${pass} pass, ${fail} fail`);
process.exit(fail ? 1 : 0);
