import puppeteer from 'puppeteer-core';
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const ORIGIN = process.env.SW_ORIGIN ?? 'http://localhost:5206';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', protocolTimeout: 300000, defaultViewport: { width: 1600, height: 1000 } });
const page = await browser.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push((e.stack || e.message).slice(0, 300)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text().slice(0, 200)); });
await page.goto(ORIGIN + '/?play=small&invlayout=vanilla', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForFunction(() => window.__swGame && window.__swGame.world && window.__swUI, { timeout: 280000, polling: 1000 });
await page.waitForFunction((sel) => document.querySelector(sel), { timeout: 300000, polling: 1000 }, '.sw-vinv');
await new Promise((r) => setTimeout(r, 700));
const out = await page.evaluate(async () => {
  const g = window.__swGame;
  const ui = window.__swUI;
  document.getElementById('sw-welcome-announce')?.remove();
  const steps = [];
  const snap = (t) => steps.push(`t=${t} dialogEl=${!!document.querySelector('.sw-npc-dialog')} btns=${document.querySelectorAll('.sw-npc-dialog .sw-npc-btn').length} session=${!!g.dialogNpc} panel=${ui.invPanel.style.display}`);
  const { TownNPC } = await import('/src/entities/TownNPC.ts');
  const guide = new TownNPC('guide', g.player.x + 40, g.world.groundLevel * 16 - 48);
  guide.home = null;
  g.entities.add(guide, 'npcs');
  window.__fx23Guide = guide;
  g.openNpcDialog(guide);
  snap('0');
  await new Promise((r) => setTimeout(r, 50)); snap('50');
  await new Promise((r) => setTimeout(r, 150)); snap('200');
  await new Promise((r) => setTimeout(r, 400)); snap('600');
  const dlg = document.querySelector('.sw-npc-dialog');
  steps.push('dlgHtml=' + (dlg ? dlg.outerHTML.slice(0, 300) : 'NULL'));
  return { steps, guide: { x: guide.x, y: guide.y, w: guide.w, h: guide.h, dead: guide.dead }, player: { x: g.player.x, y: g.player.y }, gl: g.world.groundLevel };
});
console.log(out.steps.join('\n'));
console.log('guide=', JSON.stringify(out.guide), 'player=', JSON.stringify(out.player), 'groundLevel=', out.gl);
console.log('errs=', errs.join(' | ').slice(0, 500));
await browser.close();
