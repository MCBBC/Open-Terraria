import puppeteer from 'puppeteer-core';
const CHROME = process.env.HOME + '/.cache/puppeteer/chrome/mac_arm-150.0.7871.24/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', defaultViewport: { width: 1280, height: 800 }, protocolTimeout: 120000 });
const page = await browser.newPage();
await page.goto((process.env.SW_ORIGIN ?? 'http://localhost:5199') + '/?play=small', { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForFunction(() => window.__swGame && window.__swGame.world && window.__swGame.renderer, { timeout: 300000, polling: 1000 });
await new Promise((r) => setTimeout(r, 1500));
const info = await page.evaluate(() => {
  const g = window.__swGame, r = g.renderer;
  return { rect: r.minimapRect, uiBlocking: g.input.uiBlocking, mmHover: r.minimapUiHover, mouse: [g.input.mouseX, g.input.mouseY], style: r.mapStyle };
});
console.log('before:', JSON.stringify(info));
const pos = await page.evaluate(() => { const r = window.__swGame.renderer.minimapRect; return { x: Math.round(r.x + r.w / 2), y: Math.round(r.y + r.h / 2) }; });
await page.mouse.move(pos.x, pos.y);
await new Promise((r) => setTimeout(r, 200));
await page.mouse.down(); await new Promise((r) => setTimeout(r, 80)); await page.mouse.up();
await new Promise((r) => setTimeout(r, 400));
const after = await page.evaluate(() => { const fm = window.__swGame.renderer.fullMap; return { open: fm.open, zoom: fm.zoom, panX: fm.panX, amx: fm.anchorMX }; });
console.log('after click at', JSON.stringify(pos), '->', JSON.stringify(after));
await browser.close();
