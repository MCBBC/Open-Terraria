// 零交互加载:只起世界空转 6s,捕获页面错误——判定 useaudit 三个 FAIL 是否存量
import puppeteer from 'puppeteer-core';
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const URL = (process.env.SW_ORIGIN ?? 'http://localhost:5199') + '/';
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', defaultViewport: { width: 1280, height: 900 } });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(URL, { waitUntil: 'networkidle0' });
await page.waitForSelector('select', { timeout: 120000 });
await page.evaluate(() => { document.querySelector('select').selectedIndex = 0; });
await page.click('button');
await page.waitForFunction(() => window.__swGame && window.__swGame.world, { timeout: 300000 });
await new Promise((r) => setTimeout(r, 6000));
console.log('load-only page errors:', JSON.stringify(errors));
console.log('player.appearance.skinVariant =', await page.evaluate(() => window.__swGame.player.appearance?.skinVariant ?? 'MISSING'));
console.log('rod 1326 in TELEPORT branch check: held 1326, useTime=0, mouseDown 300ms');
const rod = await page.evaluate(async () => {
  const g = window.__swGame; const p = g.player;
  const key = Object.keys(window.__swItems).find((k) => /^vi_1326_/.test(k));
  p.inv.slots[0] = { id: window.__swItems[key], stack: 1 };
  p.inv.selected = 0; p.useTime = 0;
  const tx = Math.floor(p.cx / 16) + 6, ty = Math.floor((p.y + p.h) / 16) - 5;
  g.world.store.setTile(tx, ty, 0);
  const cam = g.camera;
  g.input.mouseX = (tx * 16 + 8 - cam.x) * cam.zoom + cam.viewW / 2;
  g.input.mouseY = (ty * 16 + 8 - cam.y) * cam.zoom + cam.viewH / 2;
  const hp0 = p.hp, x0 = p.x;
  g.input.mouseDown = true;
  await new Promise((r) => setTimeout(r, 300));
  g.input.mouseDown = false;
  return { key, moved: Math.abs(p.x - x0), hpDrop: hp0 - p.hp, newErrors: [] };
});
console.log('rod:', JSON.stringify(rod));
console.log('page errors after rod:', JSON.stringify(errors));
await browser.close();
