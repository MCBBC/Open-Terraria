import puppeteer from 'puppeteer-core';
const ORIGIN = process.env.SW_ORIGIN ?? 'http://localhost:5199';
const browser = await puppeteer.launch({ executablePath: process.env.SW_CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', defaultViewport: { width: 1280, height: 800 }, protocolTimeout: 600000 });
const page = await browser.newPage();
page.on('console', (m) => { const t = m.text(); if (t.includes('[worldGen]') || t.includes('生成')) console.log('GEN:', t.slice(0, 160)); });
await page.goto(ORIGIN, { waitUntil: 'domcontentloaded', timeout: 180000 });
await page.waitForFunction(() => typeof window.__swFlow === 'object' && !!window.__swFlow?.newWorld, { timeout: 240000, polling: 500 });
console.log('[smoke] bridge ready, gen start', new Date().toISOString());
await page.evaluate(async () => { await window.__swFlow.newWorld('12345', 1200, 400); });
console.log('[smoke] newWorld resolved', new Date().toISOString());
await page.waitForFunction(() => !!window.__swGame, { timeout: 300000, polling: 500 });
console.log('[smoke] game ready', new Date().toISOString());
await browser.close();
process.exit(0);
