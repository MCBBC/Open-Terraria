import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:'new', args:['--no-sandbox']});
const page = await browser.newPage();
page.on('pageerror', e => console.log('ERR:', e.message));
await page.goto('http://localhost:5199', {waitUntil:'networkidle0'});
await page.type('input', 'feat4');
await page.evaluate(() => { document.querySelector('select').selectedIndex = 0; });
await page.click('button');
await page.waitForFunction(() => window.__swGame && window.__swGame.player && window.__swGame.liquid, {timeout: 300000});
await new Promise(r => setTimeout(r, 1500));
const out = await page.evaluate(async () => {
  const sleep = (ms) => new Promise(r => setTimeout(r, ms));
  const g = window.__swGame, st = g.world.store, p = g.player;
  const tiles = window.__swTiles;
  const px = Math.floor(p.cx / 16), py = Math.floor((p.y + p.h) / 16);
  const SW = tiles['v_136_switch'];
  const sx = px + 3, sy = py - 2;
  st.setTile(sx, sy, SW, 0, 0);
  const placed = st.get(sx, sy);
  const npcs = g.entities.npcs.map(n => ({ k: n.npcKey, dx: Math.round((n.cx - p.cx)/16), dy: Math.round((n.cy - p.cy)/16) }));
  const vw = g.camera.viewW, vh = g.camera.viewH;
  const [mx, my] = [(sx * 16 + 8 - g.camera.x) * g.camera.zoom + vw / 2, (sy * 16 + 8 - g.camera.y) * g.camera.zoom + vh / 2];
  g.input.mouseX = mx; g.input.mouseY = my;
  g.input.rightDown = true;
  await sleep(200);
  g.input.rightDown = false;
  await sleep(150);
  const f1 = st.frameX[st.idx(sx, sy)];
  return { placed, npcs, f1, cameraX: g.camera.x, cameraY: g.camera.y, tileUnder: g.camera ? [Math.floor((mx - vw/2)/g.camera.zoom/16 + g.camera.x/16), Math.floor((my - vh/2)/g.camera.zoom/16 + g.camera.y/16)] : null };
});
console.log(JSON.stringify(out, null, 1));
await browser.close();
